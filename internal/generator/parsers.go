package generator

import (
	"fmt"
	"strings"
	"unicode"

	"github.com/azizndao/glib/internal/scanner"
)

// capitalize capitalizes the first letter of a string
func capitalize(s string) string {
	if s == "" {
		return s
	}
	runes := []rune(s)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

// generateParsers generates request/response parsers for each handler (parsers.gen.go)
func (g *Generator) generateParsers() (string, error) {
	// Track which imports are actually needed
	needsJSON := false
	needsUUID := false
	usedPackages := make(map[string]bool)

	// Analyze what imports we need
	for _, ctrl := range g.project.Controllers {
		for _, handler := range ctrl.Handlers {
			sig := handler.Signature

			// Check if JSON is used (only for request body parsing)
			if sig.RequestType != nil {
				needsJSON = true
				// Request body needs the package for type assertion
				if sig.RequestType.PackageName != "" && sig.RequestType.PackagePath != "" {
					usedPackages[sig.RequestType.PackagePath] = true
				}
			}

			// Check if UUID is used in path params
			for _, param := range sig.PathParams {
				if param.Type.PackageName == "uuid" {
					needsUUID = true
				}
			}
		}
	}

	// Build imports list
	var imports []string
	if needsJSON {
		imports = append(imports, "encoding/json")
	}
	imports = append(imports, "net/http")
	if needsUUID {
		imports = append(imports, "github.com/google/uuid")
	}
	for pkgPath := range usedPackages {
		if pkgPath != g.pkgName {
			imports = append(imports, pkgPath)
		}
	}

	// Start building the file
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by glib. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", g.pkgName)
	b.WriteString("import (\n")
	for _, imp := range imports {
		fmt.Fprintf(&b, "\t\"%s\"\n", imp)
	}
	b.WriteString(")\n\n")

	// Generate handler wrappers for each handler
	for _, ctrl := range g.project.Controllers {
		for _, handler := range ctrl.Handlers {
			wrapper, err := g.generateHandlerWrapper(ctrl, handler)
			if err != nil {
				return "", err
			}
			b.WriteString(wrapper)
		}
	}

	return b.String(), nil
}

// generateHandlerWrapper generates a wrapper function for a handler
func (g *Generator) generateHandlerWrapper(ctrl *scanner.Controller, handler *scanner.Handler) (string, error) {
	// Use PackageName + Name to ensure uniqueness across multiple controllers
	// e.g., "handlePostControllerIndex", "handleCommentControllerIndex"
	wrapperName := fmt.Sprintf("handle%s%s%s",
		capitalize(ctrl.PackageName),
		ctrl.Name,
		handler.Name)
	ctrlField := g.controllerFieldName(ctrl)

	// Generate function signature
	var b strings.Builder
	fmt.Fprintf(&b, "// %s wraps %s.%s\n", wrapperName, ctrl.Name, handler.Name)
	fmt.Fprintf(&b, "func %s(c *container) http.HandlerFunc {\n", wrapperName)
	b.WriteString("\treturn func(w http.ResponseWriter, r *http.Request) {\n")

	// Generate handler body based on pattern
	body, err := g.generateHandlerBody(ctrl, handler, ctrlField)
	if err != nil {
		return "", err
	}
	b.WriteString(body)

	b.WriteString("\t}\n")
	b.WriteString("}\n\n")

	return b.String(), nil
}

// generateHandlerBody generates the body of a handler based on its pattern
func (g *Generator) generateHandlerBody(ctrl *scanner.Controller, handler *scanner.Handler, ctrlField string) (string, error) {
	sig := handler.Signature

	// Select template based on pattern
	var tmplName string
	switch sig.Pattern {
	case 1, 2:
		tmplName = "pattern_1_2.tmpl"
	case 3:
		tmplName = "pattern_3.tmpl"
	case 4:
		tmplName = "pattern_4.tmpl"
	case 5:
		tmplName = "pattern_5.tmpl"
	case 6:
		tmplName = "pattern_6.tmpl"
	case 7:
		tmplName = "pattern_7.tmpl"
	case 8:
		tmplName = "pattern_8.tmpl"
	case 9:
		tmplName = "pattern_9.tmpl"
	default:
		return "", fmt.Errorf("unsupported handler pattern: %d", sig.Pattern)
	}

	data := map[string]any{
		"Controller": ctrl,
		"Handler":    handler,
		"CtrlField":  ctrlField,
	}

	return g.executeTemplate(tmplName, data)
}
